// Lưới 10 × 14 ô (x 0..9, y 0..13); pin cố định bên trái: + ở (1, 3), − ở (1, 11); đường nguồn y = 1, đường đất y = 13.
// Lưới điện (net): 0 = đất (GND), 1 = nguồn (VCC), các số khác đánh theo màn.
// tests/assembly.test.ts kiểm tra: đường đồng nối đúng mọi lỗ cùng net, không chạm net khác, lời giải chạy được,
// và các lỗi hay gặp (LED ngược, thiếu điện trở, tụ ngược...) bị bộ chấm bắt đúng.
import type { AsmLevel, Pt, Trace } from './board';

const T = (net: number, ...pts: Pt[]): Trace => ({ net, layer: 0, pts });
/** đường mặt dưới (chạy qua dưới linh kiện) */
const B = (net: number, ...pts: Pt[]): Trace => ({ net, layer: 1, pts });

const BATTERY = (volts: number) => ({ plus: [1, 3] as Pt, minus: [1, 11] as Pt, volts, net: 1 });
/** cực + của pin lên đường nguồn tới x */
const VCC = (x: number): Trace => T(1, [1, 3], [1, 1], [x, 1]);
/** cực − của pin xuống đường đất tới x */
const GND = (x: number): Trace => T(0, [1, 11], [1, 13], [x, 13]);

